function make(prefix: string, index: number, row: Row): Question {
  const [topic, type, question, correct, d1, d2, d3, reason] = row;
  const options = [correct, d1, d2, d3];
  const answer = index % 4;
  const first = options.shift()!;
  options.splice(answer, 0, first);
  return { id: `${prefix}-${index}`, topic, type, title: topic, instruction: '請根據題目選出最適合的答案。', question, options, answer, hint: hints[topic] ?? '先找出題目的關鍵條件，再逐步判斷。', explanation: `${reason}所以答案是「${correct}」。`, encouragement: '答對了！你把條件和方法連起來了。' };
}

function build(prefix: string, start: number, rows: Row[]) { return rows.slice(0, 50).map((row, index) => make(prefix, start + index, row)); }

