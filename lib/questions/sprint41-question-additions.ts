import type { QuestionCardQuestion } from '@/components/question/QuestionCard';

type Question = QuestionCardQuestion;
type Row = [string, Question['type'], string, string, string, string, string, string, string];

function make(prefix: string, index: number, row: Row): Question {
  const [topic, type, question, correct, d1, d2, d3, hint, explanation] = row;
  const options = [correct, d1, d2, d3];
  const answer = index % 4;
  const first = options.shift()!;
  options.splice(answer, 0, first);
  return { id: `${prefix}-${index}`, topic, type, title: topic, instruction: '請根據題目選出最適合的答案。', question, options, answer, hint, explanation, encouragement: '答對了！你能把方法用在新的題目中。' };
}

function build(prefix: string, start: number, rows: Row[]) { return rows.map((row, index) => make(prefix, start + index, row)); }

