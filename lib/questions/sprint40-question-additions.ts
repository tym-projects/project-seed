import type { QuestionCardQuestion } from '@/components/question/QuestionCard';

type Question = QuestionCardQuestion;

function make(
  id: string,
  topic: string,
  type: Question['type'],
  question: string,
  correct: string,
  distractors: string[],
  hint: string,
  explanation: string,
  answer: number,
): Question {
  const options = [correct, ...distractors];
  const first = options.shift()!;
  options.splice(answer, 0, first);
  return {
    id,
    topic,
    type,
    title: topic,
    instruction: '請根據題目選出最適合的答案。',
    question,
    options,
    answer,
    hint,
    explanation,
    encouragement: '答對了！你能把學到的方法用在新的題目中。',
  };
}

