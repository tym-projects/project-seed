type Question = {
  id: string;
  topic: string;
  type: 'basic' | 'application';
  title: string;
  instruction: string;
  question: string;
  options: string[];
  answer: number;
  hint: string;
  explanation: string;
  encouragement: string;
};

function make(
  id: string,
  topic: string,
  type: Question['type'],
  question: string,
  correct: string,
  distractors: string[],
  hint: string,
  explanation: string,
  answer: number,
): Question {
  const options = [correct, ...distractors];
  const first = options.shift()!;
  options.splice(answer, 0, first);
  return { id, topic, type, title: topic, instruction: '請根據題目選出最適合的答案。', question, options, answer, hint, explanation, encouragement: '答對了！你能把方法用在新的情境中。' };
}

